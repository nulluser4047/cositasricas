# Программа рисует спиральную галактику слоями цветных точек.
# Команда import загружает модуль с готовыми инструментами.
# Функцию можно вызвать через имя модуля и точку, например math.cos(...).

import turtle  # Инструменты для рисования в окне.
import colorsys  # Функции для преобразования цветов.
import math  # Синус, косинус и константы, например число пи.
import random  # Случайные числа для выбора положения, размера и яркости.

random.seed(7)  # Задаёт одну и ту же последовательность случайных чисел при каждом запуске.
TILT = 0.45  # Угол поворота галактики в радианах.

# Окно Turtle служит холстом для рисунка.
screen = turtle.Screen()
screen.setup(780, 480)  # Ширина и высота окна в пикселях.
screen.bgcolor("#03030b")  # Тёмный фон в шестнадцатеричном формате.
screen.colormode(1.0)  # Каждая составляющая RGB принимает значения от 0 до 1.

t = turtle.Turtle()  # Создаёт черепашку, которая перемещается по окну.
t.hideturtle()  # Скрывает курсор черепашки.
t.speed(0)  # Выбирает самый быстрый режим движения черепашки.
t.penup()  # Поднимает перо при перемещении между точками.

# Преобразует HSV (тон, насыщенность и яркость) в RGB (красный, зелёный и синий).
# Насыщенность равна 0.7. Яркость v по умолчанию равна 1.0.
def glow(h, v=1.0):
    # Выражение h % 1 приводит тон к одному обороту цветового круга.
    return colorsys.hsv_to_rgb(h % 1, 0.7, v)

# Перемещает курсор в точку галактики после сжатия и поворота координат.
def place(x, y):
    y *= 0.55  # Сжимает рисунок по вертикали до 55 %, придавая ему овальную форму.
    # Косинус и синус угла нужны для поворота точки вокруг центра.
    c, s = math.cos(TILT), math.sin(TILT)
    t.goto(x * c - y * s, x * s + y * c)

# Распределяет по фону 140 белых звёзд.
def stars():
    for _ in range(140):
        # x и y задают положение по горизонтали и вертикали относительно центра окна.
        x = random.randint(-385, 385)
        y = random.randint(-235, 235)
        t.goto(x, y)  # Перемещает черепашку в точку с этими координатами.
        # Функция dot получает размер и цвет. randint выбирает размер 1, 2 или 3.
        t.dot(random.randint(1, 3), "white")

# Добавляет вокруг центра 700 тусклых фиолетовых точек, изображающих пыль.
def dust():
    for _ in range(700):
        # Функция gauss чаще выбирает r вблизи нуля. Число 120 задаёт разброс.
        # Угол a охватывает почти полный оборот. Косинус и синус дают x и y.
        r = random.gauss(0, 120)
        a = random.uniform(0, 6.283)
        place(r * math.cos(a), r * math.sin(a))
        t.dot(random.randint(2, 4), glow(0.7, 0.3))

# Рисует четыре спиральных рукава по count точек в каждом.
def arms(count):
    for i in range(count):
        for k in range(4):
            d = i / count  # Доля пути от центра к краю.
            # Начало каждого рукава сдвинуто на четверть оборота.
            # Слагаемое d * 5.5 закручивает рукав по мере роста радиуса.
            a = k * math.pi / 2 + d * 5.5
            r = 10 + d * 290  # Радиус растёт по мере продвижения вдоль рукава.
            s = 4 + d * 26  # Разброс увеличивается ближе к краю.
            # Случайные сдвиги по x и y придают спирали ширину.
            x = r * math.cos(a) + random.gauss(0, s)
            y = r * math.sin(a) + random.gauss(0, s)
            place(x, y)
            # Тон меняется вдоль рукава. Яркость и размер выбираются случайно.
            hue = 0.13 - d * 0.55
            v = random.uniform(0.6, 1)
            size = random.randint(2, 4)
            t.dot(size, glow(hue, v))

# Собирает 260 золотистых точек у центра, чтобы подсветить ядро.
def core():
    for _ in range(260):
        r = random.gauss(0, 26)
        a = random.uniform(0, 6.283)
        place(r * math.cos(a), r * math.sin(a))
        t.dot(random.randint(2, 5), glow(0.12))

# Добавляет по всей галактике 40 более крупных белых звёзд.
def sparkle():
    for _ in range(40):
        r = random.gauss(0, 150)
        a = random.uniform(0, 6.283)
        place(r * math.cos(a), r * math.sin(a))
        t.dot(random.randint(5, 8), "white")

# Эти вызовы рисуют слои по порядку, от звёздного фона до ярких бликов.
stars()
dust()
arms(900)  # По 900 точек на рукав, всего 3600 точек на четыре рукава.
core()
sparkle()
t.goto(0, 0)  # Возвращает черепашку в центр окна.
t.dot(26, "#fff3c4")  # Добавляет в центре большую светлую точку.
turtle.done()  # Оставляет окно открытым, пока ты его не закроешь.
